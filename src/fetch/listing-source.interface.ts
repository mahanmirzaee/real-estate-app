// این فایل قرارداد «منبع آگهی» است؛ یعنی هر سایتی که آگهی می‌دهد باید این یک کار را بلد باشد.
// به این می‌گویند `Strategy` (استراتژی): راه‌های مختلف گرفتن آگهی (دیوار، شیپور، ...)
// همه پشت یک قرارداد می‌نشینند و بقیه‌ی کد نمی‌داند آگهی از کدام سایت آمده است؛
// فقط قرارداد را صدا می‌زند و آگهی خام تحویل می‌گیرد.

import { RawPost } from './listing.interface';

export interface ListingSource {
  // اسم منبع؛ 'divar' یا 'sheypoor'.
  readonly source: 'divar' | 'sheypoor';

  // آگهی‌های خام را می‌گیرد؛ هر منبع حداکثر دو صفحه، تا کار خیلی طول نکشد.
  fetchAll(maxPages?: number): Promise<RawPost[]>;
}
