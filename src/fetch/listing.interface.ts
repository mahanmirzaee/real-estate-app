// این فایل شکل یک آگهی را مشخص می‌کند؛ یعنی هر آگهی دقیقاً چه چیزهایی دارد.
// آگهی در برنامه‌ی ما یک «موجودیت» (`Entity` — انتیتی) است: یک شناسه دارد
// و با گذر زمان عوض می‌شود، ولی هنوز همان آگهی است.

// شکل آگهی بعد از اینکه تمیز و مرتب شد و داخل برنامه ذخیره شد.
export interface Listing {
  // شناسه‌ی یکتای آگهی در دیوار یا شیپور؛ مثل شماره‌ی پرونده‌ی یک فایل در بنگاه.
  token: string;
  // تیتر آگهی، همان چیزی که در سایت نوشته شده است.
  title: string;
  // قیمت آگهی به همان صورت متنی که سایت می‌دهد؛ مثل «رهن کامل» یا «اجاره: ۵٬۰۰۰٬۰۰۰ تومان».
  priceText: string;
  // محله‌ای که آگهی در آن است؛ مثل «مهران (سیدخندان)».
  district: string;
  // دسته‌ی آگهی به زبان کد؛ مثل 'apartment-rent'.
  category: string;
  // دسته‌ی آگهی به زبان آدم؛ مثل «رهن و اجاره آپارتمان».
  categoryLabel: string;
  // لینک باز کردن آگهی در سایت خودش.
  url: string;
  // آیا آگهی مال یک شخص است یا آژانس؟ آگهی‌های آژانس هم ذخیره می‌شوند،
  // ولی فقط برای میانگین قیمت محله؛ در لیست و جست‌وجو و اعلان نمی‌آیند.
  isPersonal: boolean;
  // آگهی از کجا آمده است؛ 'divar' یا 'sheypoor'.
  source: 'divar' | 'sheypoor';
  // تاریخی که آگهی را گرفتیم.
  fetchedAt: string;
  // تاریخ انتشار آگهی از زبان خود منبع؛ اگر منبع تاریخ نداد، خالی است
  // و `fetchedAt` (اولین دیده‌شدن) جای آن را می‌گیرد.
  publishedAt?: string | null;
  // نشانی عکس آگهی؛ اگر آگهی عکس نداشت، خالی است.
  imageUrl?: string | null;
  // همه‌ی عکس‌های آگهی برای گالری کارت؛ اگر منبع فقط یک عکس داد، همین یک عکس است.
  // اگر خالی باشد، کارت همان عکس تکی (`imageUrl`) را نشان می‌دهد.
  imageUrls?: string[] | null;
  // رهن آگهی به تومان؛ فقط برای دسته‌های اجاره پر می‌شود. اگر قیمت خوانده نشد، خالی است.
  rahnAmount?: number | null;
  // اجاره‌ی ماهانه به تومان؛ برای «رهن کامل» صفر است، نه خالی.
  ejareAmount?: number | null;
  // قیمت فروش (قیمت کل) به تومان؛ فقط برای دسته‌های خرید پر می‌شود.
  saleAmount?: number | null;
  // متراژ آگهی به متر مربع؛ اگر از تیتر یا متن خوانده نشد، خالی است.
  areaSqm?: number | null;
  // متری به تومان (قیمت کل تقسیم بر متراژ)؛ موقع خواندن لیست حساب می‌شود، ذخیره نمی‌شود.
  perMeter?: number | null;
  // میانگین متری همان محله و همان نوع؛ موقع خواندن لیست حساب می‌شود.
  // این عدد میانه است، نه میانگین حسابی، تا آگهی‌های خیلی گرون یا ارزون منحرفش نکنند.
  districtAveragePerMeter?: number | null;
  // چند آگهی در میانگین محله شمرده شده است؛ اگر کمتر از ۳ تا باشد، میانگین نشان داده نمی‌شود.
  districtAverageCount?: number | null;
  // آیا متری این آگهی بیش از ۱۰٪ زیر میانگین محله‌اش است؟ یعنی «زیر قیمت».
  belowAverage?: boolean;
  // مشتری‌هایی که این آگهی به دردشان می‌خورد؛ سمت سرور حساب می‌شود.
  // اگر خالی باشد، یعنی به درد هیچ مشتری ذخیره‌شده‌ای نمی‌خورد.
  matchedClients?: string[];
  // متن کامل آگهی؛ برای دیوار از صفحه‌ی خود آگهی می‌آید، برای شیپور از جزئیاتش.
  // آگهی‌های قدیمی که موقع ذخیره متن نداشتند، این فیلدشان خالی است.
  description?: string | null;
  // امکانات آگهی که از متن درآورده‌ایم؛ پارکینگ/انباری/آسانسور و یک ویژگی خوب.
  // اگر متن نبود، خالی است یعنی «معلوم نیست».
  features?: ListingFeatures | null;
}

// امکانات آگهی؛ همان چیزی که فایل `features.ts` (فیچرز) از روی متن درمی‌آورد.
export interface ListingFeatures {
  parking: boolean | null;
  storage: boolean | null;
  elevator: boolean | null;
  highlight: string | null;
}

// شکل خام آگهی همان‌طور که سایت تحویل می‌دهد، قبل از تمیز شدن.
export interface RawPost {
  token: string;
  title: string;
  priceText: string;
  bottomText: string;
  district: string;
  category: string;
  categoryLabel: string;
  // آگهی از کجا آمده است؛ 'divar' یا 'sheypoor'.
  source: 'divar' | 'sheypoor';
  // لینک باز کردن آگهی در سایت خودش.
  url: string;
  // اگر سایت خودش گفته باشد آگهی مال آژانس است (مثلاً فروشنده پروفایل فروشگاهی دارد)،
  // اینجا درست است و آگهی کنار گذاشته می‌شود؛ اگر سایت چیزی نگفته باشد، خالی می‌ماند
  // و فقط قانون‌های متنی تصمیم می‌گیرند.
  isAgency?: boolean;
  // تاریخ انتشار آگهی از زبان خود منبع؛ اگر منبع تاریخ نداد، خالی می‌ماند.
  publishedAt?: string;
  // نشانی عکس آگهی، اگر سایت عکس داده باشد؛ اگر نداده باشد، خالی می‌ماند.
  imageUrl?: string;
  // همه‌ی عکس‌های آگهی برای گالری؛ از صفحه‌ی جزئیات می‌آید.
  imageUrls?: string[];
  // متن کامل آگهی؛ برای دیوار از صفحه‌ی خود آگهی می‌آید، برای شیپور از جزئیاتش.
  // اگر متن گرفته نشد، خالی می‌ماند و امکانات آگهی «معلوم نیست» می‌شود.
  description?: string;
}
