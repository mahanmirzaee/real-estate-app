// این فایل شکل یک آگهی را مشخص می‌کند؛ یعنی هر آگهی دقیقاً چه چیزهایی دارد.
// آگهی در برنامه‌ی ما یک «موجودیت» (`Entity` — انتیتی) است: یک شناسه دارد
// و با گذر زمان عوض می‌شود، ولی هنوز همان آگهی است.

// شکل آگهی بعد از اینکه تمیز و مرتب شد و داخل برنامه ذخیره شد.
export interface Listing {
  // شناسه‌ی یکتای آگهی در دیوار؛ مثل شماره‌ی پرونده‌ی یک فایل در بنگاه.
  token: string;
  // تیتر آگهی، همان چیزی که در دیوار نوشته شده است.
  title: string;
  // قیمت آگهی به همان صورت متنی که دیوار می‌دهد؛ مثل «رهن کامل» یا «اجاره: ۵٬۰۰۰٬۰۰۰ تومان».
  priceText: string;
  // محله‌ای که آگهی در آن است؛ مثل «مهران (سیدخندان)».
  district: string;
  // دسته‌ی آگهی به زبان کد؛ مثل 'apartment-rent'.
  category: string;
  // دسته‌ی آگهی به زبان آدم؛ مثل «رهن و اجاره آپارتمان».
  categoryLabel: string;
  // لینک باز کردن آگهی در دیوار.
  url: string;
  // آیا آگهی مال یک شخص است یا آژانس؟ در نسخه‌ی اول فقط آگهی‌های شخصی ذخیره می‌شوند.
  isPersonal: boolean;
  // آگهی از کجا آمده است؛ در نسخه‌ی اول فقط 'divar' است و شیپور بعداً اضافه می‌شود.
  source: 'divar';
  // تاریخی که آگهی را گرفتیم.
  fetchedAt: string;
}

// شکل خام آگهی همان‌طور که دیوار تحویل می‌دهد، قبل از تمیز شدن.
export interface RawPost {
  token: string;
  title: string;
  priceText: string;
  bottomText: string;
  district: string;
  category: string;
  categoryLabel: string;
}
