// شکل یک محله‌ی پیکربندی‌شده؛ همان چیزی که در جدول `AppConfig` (اپ‌کانفیگ)
// زیر کلید `districts` (دیستریکتس) به شکل `JSON` (جیسون) ذخیره می‌شود.
// شناسه‌ی دیوار (`id` — آیدی) برای جست‌وجو لازم است؛ شناسه‌ی شیپور (`sheypoorId` — شیپور آیدی)
// و اسم شیپور (`sheypoorName` — شیپور نیم) اختیاری‌اند — اگر نباشند، شیپور آن محله را نمی‌گردد،
// ولی دیوار می‌گردد.

export interface DistrictConfig {
  // شناسه‌ی عددی محله در دیوار؛ مثل '95' برای مهران.
  id: string;
  // اسم محله؛ مثل 'مهران'.
  name: string;
  // شناسه‌ی محله در شیپور؛ اگر خالی باشد، شیپور این محله را نمی‌گردد.
  sheypoorId?: string;
  // اسمی که شیپور برای این محله می‌نویسد؛ مثل 'مهران - منطقه 4'.
  // اگر خالی باشد، آگهی شیپور این محله با اسم دیوارش شناخته نمی‌شود.
  sheypoorName?: string;
}
